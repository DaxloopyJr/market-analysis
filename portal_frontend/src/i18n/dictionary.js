/** English → Kiswahili when the user chose Kiswahili; anything unknown stays as it is. */
export function translate(text, lang) {
  if (lang !== 'sw' || typeof text !== 'string') return text;
  return SW[text] ?? SW[text.trim()] ?? text;
}
